function toyEncrypt(block, key, salt = 0) {
  const chars = [...block];
  const k = [...key].reduce((a, c) => a + c.charCodeAt(0), 0) + salt * 17;
  return chars.map((c, i) => ((c.charCodeAt(0) ^ ((k + i * 29) & 255)) + i * 11) & 255)
    .map(n => n.toString(16).padStart(2, '0')).join('').toUpperCase();
}

function hexToBytes(hex) {
  return (hex.match(/.{1,2}/g) || []).map(x => parseInt(x, 16));
}

function xorHex(a, b) {
  const aa = hexToBytes(a), bb = hexToBytes(b);
  return aa.map((v, i) => (v ^ (bb[i % bb.length] ?? 0)).toString(16).padStart(2, '0')).join('').toUpperCase();
}

function modelBlocks(mode, key, plaintext) {
  const clean = plaintext || 'DATA';
  const chunks = clean.match(/.{1,4}/g) || ['DATA'];
  const iv = toyEncrypt('INIT', key, 9);
  const rows = [];
  let previous = iv;
  let stream = iv;
  chunks.slice(0, 4).forEach((plain, i) => {
    const pHex = [...plain.padEnd(4, ' ')].map(c => c.charCodeAt(0).toString(16).padStart(2, '0')).join('').toUpperCase();
    let cHex = '';
    let operation = '';
    if (mode === 'ECB') {
      cHex = toyEncrypt(plain.padEnd(4, ' '), key, i);
      operation = `Eₖ(P${i + 1})`;
    } else if (mode === 'CBC') {
      const mixed = xorHex(pHex, previous);
      cHex = toyEncrypt(String.fromCharCode(...hexToBytes(mixed)), key, i);
      operation = `Eₖ(P${i + 1} ⊕ ${i === 0 ? 'IV' : `C${i}`})`;
    } else if (mode === 'CFB') {
      const encryptedFeedback = toyEncrypt(String.fromCharCode(...hexToBytes(previous)), key, i);
      cHex = xorHex(pHex, encryptedFeedback);
      operation = `P${i + 1} ⊕ Eₖ(${i === 0 ? 'IV' : `C${i}`})`;
    } else if (mode === 'OFB') {
      stream = toyEncrypt(String.fromCharCode(...hexToBytes(stream)), key, i);
      cHex = xorHex(pHex, stream);
      operation = `P${i + 1} ⊕ S${i + 1}`;
    } else {
      const counter = `CTR${i + 1}`;
      stream = toyEncrypt(counter, key, i + 2);
      cHex = xorHex(pHex, stream);
      operation = `P${i + 1} ⊕ Eₖ(${counter})`;
    }
    rows.push({ block: `P${i + 1}`, plaintext: plain.padEnd(4, ' '), hex: pHex, ciphertext: cHex, operation });
    previous = cHex;
  });
  return { rows, iv };
}

